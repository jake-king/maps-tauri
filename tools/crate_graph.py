"""The workspace's crate graph as a Mermaid flowchart, from `cargo metadata`: the four crates, the
dependencies between them, and each one's direct third-party dependencies (normal ones only; a
dashed edge is optional, behind a feature). The book includes the result (book/src/crates.mmd).

    python3 tools/crate_graph.py            print it
    python3 tools/crate_graph.py --write    rewrite book/src/crates.mmd
    python3 tools/crate_graph.py --check    exit 1 if book/src/crates.mmd differs from a fresh run
"""

import json
import pathlib
import subprocess
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "book" / "src" / "crates.mmd"


def node_id(name):
    return name.replace("-", "_")


def graph():
    meta = json.loads(
        subprocess.run(
            ["cargo", "metadata", "--no-deps", "--format-version", "1", "--locked"],
            check=True,
            capture_output=True,
            text=True,
            cwd=OUT.parent.parent.parent,
        ).stdout
    )
    members = sorted(p["name"] for p in meta["packages"])
    lines = [
        "%% generated by tools/crate_graph.py from cargo metadata; the gate checks it is current",
        "flowchart TD",
    ]
    lines += [f"  {node_id(m)}[{m}]" for m in members]
    external = set()
    edges = []
    for p in sorted(meta["packages"], key=lambda p: p["name"]):
        for d in sorted(p["dependencies"], key=lambda d: d["name"]):
            if (
                d.get("kind") is not None
            ):  # dev and build dependencies are not part of the shape
                continue
            arrow = "-.->" if d.get("optional") else "-->"
            edges.append(f"  {node_id(p['name'])} {arrow} {node_id(d['name'])}")
            if d["name"] not in members:
                external.add(d["name"])
    lines += [f"  {node_id(e)}([{e}])" for e in sorted(external)]
    lines += edges
    lines += [f"  class {','.join(node_id(e) for e in sorted(external))} external"]
    lines += ["  classDef external fill:#eee,stroke:#999,color:#333"]
    return "\n".join(lines) + "\n"


def main():
    text = graph()
    if sys.argv[1:] == ["--write"]:
        OUT.write_text(text)
    elif sys.argv[1:] == ["--check"]:
        if not OUT.exists() or OUT.read_text() != text:
            print(
                f"crate_graph: {OUT.name} is stale; run python3 tools/crate_graph.py --write"
            )
            return 1
        print(f"crate_graph: {OUT.name} is current")
    elif sys.argv[1:]:
        print(__doc__, file=sys.stderr)
        return 2
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
